"""LaTeX exporter.

The Writer agent emits prose using paper-specified `[Author, Year]` citations.
This exporter keeps those markers verbatim in the body (paper §2.2.3: "[Author,
Year] citation format ensures compatibility with academic publishing standards")
and appends a numbered \\thebibliography of cited papers, ordered by appearance.

It also writes a sibling JSON file with the full evaluator output, clustering
metrics, search statistics, and logs.
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

from ..state import Paper, SurveyState


PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage{hyperref}
\usepackage{microtype}
\usepackage{enumitem}
\usepackage{titlesec}
\setlength{\parskip}{0.5em}
\setlength{\parindent}{0pt}
\title{%s}
\author{Generated by Agentic AutoSurvey \\\\ (multi-agent reimplementation of arXiv:2509.18661)}
\date{%s}
"""


# These LaTeX special chars must be escaped, but ONLY in content (not in
# inline [Author, Year] markers which already use plain ASCII).
def _latex_escape(s: str) -> str:
    return (
        s.replace("\\", r"\textbackslash{}")
         .replace("&", r"\&")
         .replace("%", r"\%")
         .replace("$", r"\$")
         .replace("#", r"\#")
         .replace("_", r"\_")
         .replace("{", r"\{")
         .replace("}", r"\}")
         .replace("~", r"\~{}")
         .replace("^", r"\^{}")
    )


def _escape_content_preserving_citations(text: str) -> str:
    """Escape LaTeX specials in body text but keep [Author, Year] markers intact."""
    if not text:
        return ""
    # Citations look like [Lewis et al., 2020] or [Smith and Doe, 2022a].
    cite_re = re.compile(r"\[[^\[\]\n]+,\s*(?:\d{4}[a-z]?|n\.d\.)\]")
    pieces: list[str] = []
    last = 0
    for m in cite_re.finditer(text):
        pieces.append(_latex_escape(text[last:m.start()]))
        pieces.append(m.group(0))   # citation marker — keep raw
        last = m.end()
    pieces.append(_latex_escape(text[last:]))
    return "".join(pieces)


def _format_authors(authors: list[str]) -> str:
    if not authors:
        return "Unknown"
    if len(authors) > 6:
        return ", ".join(authors[:6]) + ", et al."
    return ", ".join(authors)


def _bibitems(refs: list[Paper]) -> str:
    lines = []
    for i, paper in enumerate(refs, 1):
        authors = _latex_escape(_format_authors(paper.get("authors", [])))
        title = _latex_escape(paper.get("title", ""))
        year = paper.get("year") or "n.d."
        venue = _latex_escape(paper.get("venue") or paper.get("source", ""))
        url = paper.get("url") or ""
        url_part = f" \\url{{{url}}}" if url else ""
        key = paper.get("citation_key") or ""
        prefix = _latex_escape(key) + " " if key else ""
        lines.append(
            f"\\bibitem{{ref{i}}} {prefix}{authors}. {title}. \\emph{{{venue}}}, {year}.{url_part}"
        )
    return "\n".join(lines)


_SECTION_HEADINGS = {
    "intro": "Introduction",
    "cluster": None,        # use draft.title
    "cross_cutting": "Cross-Cutting Analysis",
    "future": "Future Directions",
    "conclusion": "Conclusion",
}


def export_latex(state: SurveyState, output_dir: str | Path) -> Path:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    topic = state["topic"]
    safe_topic = re.sub(r"[^A-Za-z0-9_]+", "_", topic).strip("_")[:60] or "survey"
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    stem = f"{safe_topic}_{stamp}"
    tex_path = output_dir / f"{stem}.tex"
    eval_path = output_dir / f"{stem}.eval.json"

    refs = state.get("references", [])
    abstract = _escape_content_preserving_citations(state.get("abstract_text", ""))

    body_parts: list[str] = []
    for sec in state.get("sections", []):
        heading = _SECTION_HEADINGS.get(sec["kind"]) or sec["title"]
        content = _escape_content_preserving_citations(sec["content"])
        body_parts.append(f"\\section{{{_latex_escape(heading)}}}\n{content}\n")

    title = f"A Survey on {_latex_escape(topic)}"
    today = datetime.now().strftime("%B %d, %Y")
    preamble = PREAMBLE % (title, today)

    tex = (
        preamble
        + "\\begin{document}\n\\maketitle\n\n"
        + "\\begin{abstract}\n" + abstract + "\n\\end{abstract}\n\n"
        + "\n".join(body_parts)
        + "\\begin{thebibliography}{99}\n"
        + _bibitems(refs)
        + "\n\\end{thebibliography}\n"
        + "\\end{document}\n"
    )
    tex_path.write_text(tex, encoding="utf-8")

    report = {
        "topic": topic,
        "generated_at": stamp,
        "search_queries": state.get("search_queries", []),
        "search_statistics": state.get("search_statistics", {}),
        "n_papers_kept": len(state.get("papers", [])),
        "clusters": [
            {"id": c["cluster_id"], "name": c["name"], "key_terms": c.get("key_terms", []),
             "size": c.get("size", len(c.get("paper_ids", [])))}
            for c in state.get("clusters", [])
        ],
        "cluster_quality_metrics": state.get("cluster_quality_metrics", {}),
        "cluster_relationships": state.get("cluster_relationships", []),
        "outliers": state.get("outliers", []),
        "n_references_cited": len(refs),
        "evaluation": state.get("evaluation"),
        "logs": state.get("logs", []),
    }
    eval_path.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")

    return tex_path
